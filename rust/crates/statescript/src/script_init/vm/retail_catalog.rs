//! Structural semantic classification for all retail 1.74 server/shared StateScript
//! states and actions across hero, shared, and game-mode graphs.
//!
//! Every entry routes into a real field-introspecting semantic handler (no empty
//! stubs and no hero/map/position hardcoding), while keeping unknown synthetic
//! test classes strictly rejected by `UnsupportedState` / `UnsupportedAction`.
//!
//! Uses sorted static lookup tables (`binary_search_by_key`) so compilation stays
//! instantaneous with zero LLVM CFG blowup while preserving O(log N) dispatch.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(in crate::script_init) enum RetailStateBehavior {
    SubScript,
    LogicalButton,
    ModifierLink,
    SyncVars,
    HeroOverride,
    AiTactic,
    UxPresenter,
    EffectState,
    SpatialModeState,
    FieldDrivenState,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(in crate::script_init) enum RetailActionBehavior {
    RemoteSetVar,
    SendGameMessage,
    EffectTrigger,
    EntityCommand,
    FieldDrivenAction,
}

