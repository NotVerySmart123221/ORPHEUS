pub(in crate::script_init) fn classify_retail_state(class: &str) -> Option<RetailStateBehavior> {
    if let Ok(idx) = SPECIAL_STATES.binary_search_by_key(&class, |&(k, _)| k) {
        return Some(SPECIAL_STATES[idx].1);
    }
    if FIELD_DRIVEN_STATES.binary_search(&class).is_ok() {
        return Some(RetailStateBehavior::FieldDrivenState);
    }
    None
}

pub(in crate::script_init) fn classify_retail_action(class: &str) -> Option<RetailActionBehavior> {
    if let Ok(idx) = SPECIAL_ACTIONS.binary_search_by_key(&class, |&(k, _)| k) {
        return Some(SPECIAL_ACTIONS[idx].1);
    }
    if FIELD_DRIVEN_ACTIONS.binary_search(&class).is_ok() {
        return Some(RetailActionBehavior::FieldDrivenAction);
    }
    None
}

