def posed(volumes, position, yaw):
    """The volumes in world space for a body at position turned yaw radians (model +Z to (sin, 0, cos))."""
    s, c = math.sin(yaw), math.cos(yaw)
    place = lambda p: (position[0] + p[0] * c + p[2] * s, position[1] + p[1], position[2] - p[0] * s + p[2] * c)
    return [(place(a), place(b), radius, critical) for a, b, radius, critical in volumes]


def ray(volumes, origin, direction, max_distance=math.inf):
    """(distance, critical) of the nearest posed volume the ray enters, or None."""
    hits = [(d, critical) for a, b, radius, critical in volumes
        if (d := ray_capsule_distance(origin, direction, a, b, radius, max_distance)) is not None]
    return min(hits, default=None)


def touches(volumes, point, margin=0.0):
    """Whether point lies within margin of any posed volume."""
    return any(segment_distance(point, a, b) <= radius + margin for a, b, radius, _ in volumes)
